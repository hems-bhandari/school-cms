    CASE WHEN homework_assigned > 0 THEN homework_returned::numeric / homework_assigned END
  ) STORED,
  exam_held boolean NOT NULL DEFAULT false,
  full_marks numeric(8,2) CHECK (full_marks >= 0),
  pass_marks numeric(8,2) CHECK (pass_marks >= 0),
  exam_boys integer CHECK (exam_boys >= 0),
  exam_girls integer CHECK (exam_girls >= 0),
  passed_boys integer CHECK (passed_boys >= 0),
  passed_girls integer CHECK (passed_girls >= 0),
  total_marks_sum numeric(12,2) CHECK (total_marks_sum >= 0),
  below_pass_count integer CHECK (below_pass_count >= 0),
  appeared integer GENERATED ALWAYS AS (COALESCE(exam_boys, 0) + COALESCE(exam_girls, 0)) STORED,
  pass_rate numeric(7,4) GENERATED ALWAYS AS (
    CASE WHEN COALESCE(exam_boys, 0) + COALESCE(exam_girls, 0) > 0
      THEN (COALESCE(passed_boys, 0) + COALESCE(passed_girls, 0))::numeric /
        (COALESCE(exam_boys, 0) + COALESCE(exam_girls, 0)) END
  ) STORED,
  avg_pct numeric(7,2) GENERATED ALWAYS AS (
    CASE WHEN (COALESCE(exam_boys, 0) + COALESCE(exam_girls, 0)) > 0 AND full_marks > 0
      THEN total_marks_sum * 100 / ((COALESCE(exam_boys, 0) + COALESCE(exam_girls, 0)) * full_marks) END
  ) STORED,
  at_risk_pct numeric(7,4) GENERATED ALWAYS AS (
    CASE WHEN COALESCE(exam_boys, 0) + COALESCE(exam_girls, 0) > 0
      THEN below_pass_count::numeric / (COALESCE(exam_boys, 0) + COALESCE(exam_girls, 0)) END
  ) STORED,
  baseline_average numeric(5,2) CHECK (baseline_average BETWEEN 0 AND 100),
  target_average numeric(5,2) CHECK (target_average BETWEEN 0 AND 100),
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (month_code, class_id, subject_id)
