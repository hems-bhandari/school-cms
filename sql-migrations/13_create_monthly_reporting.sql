-- Public teachers submit through this function only. It validates the private
-- teacher code and the fixed-list assignment before inserting.
CREATE OR REPLACE FUNCTION public.submit_monthly_report(
  p_report_type text,
  p_teacher_code text,
  p_payload jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_teacher_id integer;
  v_class_id smallint;
  v_subject_id smallint;
  v_month_code text := p_payload ->> 'month_code';
  v_session_year smallint := NULLIF(p_payload ->> 'session_year', '')::smallint;
  v_id bigint;
  v_expected integer;
BEGIN
  SELECT teacher_id INTO v_teacher_id
  FROM public.teacher_report_access
  WHERE upper(teacher_code) = upper(trim(p_teacher_code));

  IF v_teacher_id IS NULL OR v_teacher_id <> NULLIF(p_payload ->> 'teacher_id', '')::integer THEN
    RAISE EXCEPTION 'Teacher ID and selected teacher do not match';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.academic_months
    WHERE code = v_month_code AND session_year = v_session_year
  ) THEN
    RAISE EXCEPTION 'Invalid academic month';
  END IF;

  v_class_id := NULLIF(p_payload ->> 'class_id', '')::smallint;
  v_subject_id := NULLIF(p_payload ->> 'subject_id', '')::smallint;

  IF p_report_type = 'subject' THEN
    IF NOT EXISTS (
      SELECT 1 FROM public.class_subject
      WHERE class_id = v_class_id AND subject_id = v_subject_id
        AND teacher_id = v_teacher_id AND is_active
    ) THEN
      RAISE EXCEPTION 'The selected class and subject are not assigned to this teacher';
    END IF;

    INSERT INTO public.subject_monthly_reports (
      session_year, month_code, teacher_id, class_id, subject_id,
      student_boys, student_girls, course_completed, course_planned,
      scheduled_periods, taught_periods, homework_assigned, homework_returned,
      exam_held, full_marks, pass_marks, exam_boys, exam_girls, passed_boys,
      passed_girls, total_marks_sum, below_pass_count, baseline_average,
      target_average, payload
    ) VALUES (
      v_session_year, v_month_code, v_teacher_id, v_class_id, v_subject_id,
      COALESCE(NULLIF(p_payload ->> 'student_boys', '')::integer, 0),
      COALESCE(NULLIF(p_payload ->> 'student_girls', '')::integer, 0),
      NULLIF(p_payload ->> 'course_completed', '')::numeric,
      NULLIF(p_payload ->> 'course_planned', '')::numeric,
      NULLIF(p_payload ->> 'scheduled_periods', '')::integer,
      NULLIF(p_payload ->> 'taught_periods', '')::integer,
      NULLIF(p_payload ->> 'homework_assigned', '')::integer,
      NULLIF(p_payload ->> 'homework_returned', '')::integer,
      COALESCE((p_payload ->> 'exam_held') = 'भयो', false),
      NULLIF(p_payload ->> 'full_marks', '')::numeric,
      NULLIF(p_payload ->> 'pass_marks', '')::numeric,
      NULLIF(p_payload ->> 'exam_boys', '')::integer,
      NULLIF(p_payload ->> 'exam_girls', '')::integer,
      NULLIF(p_payload ->> 'passed_boys', '')::integer,
      NULLIF(p_payload ->> 'passed_girls', '')::integer,
      NULLIF(p_payload ->> 'total_marks_sum', '')::numeric,
      NULLIF(p_payload ->> 'below_pass_count', '')::integer,
      COALESCE(
        NULLIF(p_payload ->> 'baseline_average', '')::numeric,
        (SELECT baseline_average FROM public.subject_monthly_reports
          WHERE session_year = v_session_year AND class_id = v_class_id AND subject_id = v_subject_id
            AND baseline_average IS NOT NULL ORDER BY month_code LIMIT 1)
      ),
      COALESCE(
        NULLIF(p_payload ->> 'target_average', '')::numeric,
        (SELECT target_average FROM public.subject_monthly_reports
          WHERE session_year = v_session_year AND class_id = v_class_id AND subject_id = v_subject_id
            AND target_average IS NOT NULL ORDER BY month_code LIMIT 1)
      ),
      p_payload
    ) RETURNING id INTO v_id;

  ELSIF p_report_type = 'class' THEN
    IF NOT EXISTS (
      SELECT 1 FROM public.school_classes
      WHERE id = v_class_id AND class_teacher_id = v_teacher_id AND is_active
    ) THEN
      RAISE EXCEPTION 'The selected class is not assigned to this class teacher';
    END IF;

    INSERT INTO public.class_monthly_reports (
      session_year, month_code, teacher_id, class_id, start_boys, start_girls,
      new_boys, new_girls, left_boys, left_girls, school_days,
      present_student_days_boys, present_student_days_girls, under_75_count,
      dropout_students, chronic_absentees, baseline_average, target_average, payload
    ) VALUES (
      v_session_year, v_month_code, v_teacher_id, v_class_id,
      COALESCE(NULLIF(p_payload ->> 'start_boys', '')::integer, 0),
      COALESCE(NULLIF(p_payload ->> 'start_girls', '')::integer, 0),
      COALESCE(NULLIF(p_payload ->> 'new_boys', '')::integer, 0),
      COALESCE(NULLIF(p_payload ->> 'new_girls', '')::integer, 0),
      COALESCE(NULLIF(p_payload ->> 'left_boys', '')::integer, 0),
      COALESCE(NULLIF(p_payload ->> 'left_girls', '')::integer, 0),
      NULLIF(p_payload ->> 'school_days', '')::integer,
      NULLIF(p_payload ->> 'present_boys', '')::integer,
      NULLIF(p_payload ->> 'present_girls', '')::integer,
      NULLIF(p_payload ->> 'under_75_count', '')::integer,
      COALESCE(p_payload -> 'dropout_students', '[]'::jsonb),
      COALESCE(p_payload -> 'chronic_absentees', '[]'::jsonb),
      COALESCE(
        NULLIF(p_payload ->> 'baseline_average', '')::numeric,
        (SELECT baseline_average FROM public.class_monthly_reports
          WHERE session_year = v_session_year AND class_id = v_class_id
            AND baseline_average IS NOT NULL ORDER BY month_code LIMIT 1)
      ),
      COALESCE(
        NULLIF(p_payload ->> 'target_average', '')::numeric,
        (SELECT target_average FROM public.class_monthly_reports
          WHERE session_year = v_session_year AND class_id = v_class_id
            AND target_average IS NOT NULL ORDER BY month_code LIMIT 1)
      ),
      p_payload
    ) RETURNING id INTO v_id;

  ELSIF p_report_type = 'incharge' THEN
    IF (p_payload ->> 'level') NOT IN ('आधारभूत', 'माध्यमिक') THEN
      RAISE EXCEPTION 'Invalid school level';
    END IF;

    SELECT count(*) INTO v_expected
    FROM public.class_subject cs
    JOIN public.school_classes c ON c.id = cs.class_id
    WHERE cs.is_active AND c.is_active AND c.level = p_payload ->> 'level';

    INSERT INTO public.incharge_monthly_reports (
      session_year, month_code, teacher_id, level, expected_reports,
      on_time_reports, observation_count, observations, teacher_absent_days,
      vacant_periods, substituted_periods, payload
    ) VALUES (
      v_session_year, v_month_code, v_teacher_id, p_payload ->> 'level', v_expected,
      COALESCE(NULLIF(p_payload ->> 'on_time_reports', '')::integer, 0),
      COALESCE(NULLIF(p_payload ->> 'observation_count', '')::integer, 0),
      COALESCE(p_payload -> 'observations', '[]'::jsonb),
      COALESCE(NULLIF(p_payload ->> 'teacher_absent_days', '')::integer, 0),
      COALESCE(NULLIF(p_payload ->> 'vacant_periods', '')::integer, 0),
      COALESCE(NULLIF(p_payload ->> 'substituted_periods', '')::integer, 0),
      p_payload
    ) RETURNING id INTO v_id;
  ELSE
    RAISE EXCEPTION 'Unknown report type';
  END IF;

  RETURN jsonb_build_object('id', v_id, 'report_type', p_report_type);
END;
$$;

REVOKE ALL ON FUNCTION public.submit_monthly_report(text, text, jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.submit_monthly_report(text, text, jsonb) TO anon, authenticated;

CREATE OR REPLACE VIEW public.kpi_attendance_by_class_gender
WITH (security_invoker = true) AS
SELECT r.month_code, c.grade_number, c.name_ne AS class_name,
  round(r.attendance_rate_boys * 100, 1) AS boys_pct,
  round(r.attendance_rate_girls * 100, 1) AS girls_pct
FROM public.class_monthly_reports r JOIN public.school_classes c ON c.id = r.class_id;

CREATE OR REPLACE VIEW public.kpi_period_delivery_by_teacher
WITH (security_invoker = true) AS
SELECT r.month_code, t.name_ne AS teacher_name,
  sum(r.taught_periods) AS taught_periods, sum(r.scheduled_periods) AS scheduled_periods,
  round(sum(r.taught_periods)::numeric * 100 / NULLIF(sum(r.scheduled_periods), 0), 1) AS delivery_pct
FROM public.subject_monthly_reports r JOIN public.teachers t ON t.id = r.teacher_id
GROUP BY r.month_code, t.id, t.name_ne;

CREATE OR REPLACE VIEW public.kpi_course_progress_by_subject
WITH (security_invoker = true) AS
SELECT r.month_code, s.name_ne AS subject_name,
  round(avg(r.course_completed), 1) AS completed_pct,
  round(avg(r.course_planned), 1) AS planned_pct,
  round(avg(r.course_variance), 1) AS variance_pct
FROM public.subject_monthly_reports r JOIN public.school_subjects s ON s.id = r.subject_id
GROUP BY r.month_code, s.id, s.name_ne;

CREATE OR REPLACE VIEW public.kpi_homework_feedback_by_teacher
WITH (security_invoker = true) AS
SELECT r.month_code, t.name_ne AS teacher_name,
  sum(r.homework_returned) AS returned_count, sum(r.homework_assigned) AS assigned_count,
  round(sum(r.homework_returned)::numeric * 100 / NULLIF(sum(r.homework_assigned), 0), 1) AS feedback_pct
FROM public.subject_monthly_reports r JOIN public.teachers t ON t.id = r.teacher_id
GROUP BY r.month_code, t.id, t.name_ne;

CREATE OR REPLACE VIEW public.kpi_assessment_by_class_subject
WITH (security_invoker = true) AS
SELECT r.month_code, c.name_ne AS class_name, s.name_ne AS subject_name,
  round(r.avg_pct, 1) AS average_pct, round(r.pass_rate * 100, 1) AS pass_pct,
  round(r.at_risk_pct * 100, 1) AS at_risk_pct
FROM public.subject_monthly_reports r
JOIN public.school_classes c ON c.id = r.class_id
JOIN public.school_subjects s ON s.id = r.subject_id
WHERE r.exam_held;

CREATE OR REPLACE VIEW public.kpi_target_vs_actual
WITH (security_invoker = true) AS
SELECT r.month_code, c.name_ne AS class_name, s.name_ne AS subject_name,
  r.target_average AS target_pct, round(r.avg_pct, 1) AS actual_pct,
  round(r.avg_pct - r.target_average, 1) AS variance_pct
FROM public.subject_monthly_reports r
JOIN public.school_classes c ON c.id = r.class_id
JOIN public.school_subjects s ON s.id = r.subject_id
WHERE r.exam_held AND r.target_average IS NOT NULL;

CREATE OR REPLACE VIEW public.kpi_observations_by_coordinator
WITH (security_invoker = true) AS
SELECT r.month_code, t.name_ne AS coordinator_name, r.level, r.observation_count
FROM public.incharge_monthly_reports r JOIN public.teachers t ON t.id = r.teacher_id;

CREATE OR REPLACE VIEW public.kpi_student_followup
WITH (security_invoker = true) AS
SELECT r.month_code, c.name_ne AS class_name,
  jsonb_array_length(r.dropout_students) AS dropout_count,
  jsonb_array_length(r.chronic_absentees) AS chronic_absentee_count,
  COALESCE((
    SELECT round(count(*) FILTER (WHERE item ->> 'result' IN ('विद्यालय फर्कियो', 'आंशिक सुधार'))::numeric * 100 /
      NULLIF(count(*), 0), 1)
    FROM jsonb_array_elements(r.chronic_absentees) item
  ), 0) AS followup_closure_pct
FROM public.class_monthly_reports r JOIN public.school_classes c ON c.id = r.class_id;

GRANT SELECT ON public.school_classes, public.school_subjects, public.class_subject, public.academic_months TO anon, authenticated;
GRANT SELECT ON public.teacher_report_access TO authenticated;
GRANT SELECT ON public.subject_monthly_reports, public.class_monthly_reports, public.incharge_monthly_reports TO authenticated;
GRANT SELECT ON public.kpi_attendance_by_class_gender, public.kpi_period_delivery_by_teacher,
  public.kpi_course_progress_by_subject, public.kpi_homework_feedback_by_teacher,
  public.kpi_assessment_by_class_subject, public.kpi_target_vs_actual,
  public.kpi_observations_by_coordinator, public.kpi_student_followup TO authenticated;

COMMIT;
