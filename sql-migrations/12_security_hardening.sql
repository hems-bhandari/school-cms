        AND lower(storage.extension(name)) IN ('pdf', 'doc', 'docx', 'xls', 'xlsx', 'ppt', 'pptx', 'txt'))
    )
  );

-- Record a download without exposing general UPDATE access to public users.
CREATE OR REPLACE FUNCTION public.increment_document_download(document_id integer)
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = ''
AS $$
  UPDATE public.documents
  SET download_count = download_count + 1
  WHERE id = document_id AND is_public = true
$$;
REVOKE ALL ON FUNCTION public.increment_document_download(integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.increment_document_download(integer) TO anon, authenticated;

