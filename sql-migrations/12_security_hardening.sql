-- Only server-managed app metadata can grant administrator access. Never put
-- this role in user_metadata, which users can change themselves.
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = ''
AS $$
  SELECT COALESCE((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin', false)
$$;

REVOKE ALL ON FUNCTION public.is_admin() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_admin() TO authenticated;

-- The original migration set omitted this table even though the app uses it.
CREATE TABLE IF NOT EXISTS public.about (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_en text,
  content_ne text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.about ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE policy_record record;
BEGIN
  FOR policy_record IN
    SELECT policyname FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'about'
  LOOP
    EXECUTE format('DROP POLICY %I ON public.about', policy_record.policyname);
  END LOOP;
END $$;
CREATE POLICY "Anyone can view about" ON public.about FOR SELECT USING (true);
CREATE POLICY "Admins can manage about" ON public.about FOR ALL TO authenticated
  USING ((SELECT public.is_admin())) WITH CHECK ((SELECT public.is_admin()));

